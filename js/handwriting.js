const parsed = {};
function glyph(ch) {
    if (!(ch in GLYPHS)) ch = ch.toLowerCase() in GLYPHS ? ch.toLowerCase() : '?';
    if (!parsed[ch]) {
        const [adv, data] = GLYPHS[ch];
        const strokes = data ? data.split('|').map(s => {
            const n = s.split(' ').map(Number);
            const pts = [];
            for (let i = 0; i < n.length; i += 2) pts.push([n[i] / 1000, -n[i + 1] / 1000]);
            return pts;
        }) : [];
        parsed[ch] = { adv: adv / 1000, strokes };
    }
    return parsed[ch];
}

// Lay out a line of text. Units are em; baseline at y = 0, ascenders go negative.
// A little jitter on each letter keeps it from looking typeset.
export function writeText(text, { tracking = -0.02, jitter = 0.012 } = {}) {
    const strokes = [];
    let x = 0;
    for (const ch of text) {
        const g = glyph(ch);
        const dy = (Math.random() - 0.5) * jitter * 2;
        g.strokes.forEach(s => strokes.push(s.map(([px, py]) => [px + x, py + dy])));
        x += g.adv + tracking;
    }
    return strokes;
}

// --- doodles: all drawn inside a w x h box -------------------------------------

const wobble = (a = 1) => (Math.random() - 0.5) * a;

function sample(n, fn) {
    const pts = [];
    for (let i = 0; i <= n; i++) pts.push(fn(i / n));
    return pts;
}

const DOODLES = {
    // A loose wavy underline, with a short second pass
    underline(w, h) {
        const a = h * 0.18;
        const p1 = Math.random() * 2, p2 = Math.random() * 2;
        const first = sample(40, t => [t * w, h * 0.45 + Math.sin(t * Math.PI * 3 + p1) * a + Math.sin(t * 7 + p2) * a * 0.2]);
        const second = sample(20, t => [w * 0.12 + t * w * 0.72, h * 0.78 + Math.sin(t * Math.PI * 2 + 1) * a * 0.5]);
        return [first, second];
    },

    // Straight-ish underline that overshoots
    strike(w, h) {
        return [sample(16, t => [t * w, h * 0.55 - t * h * 0.15 + wobble(h * 0.08)])];
    },

    // The "I circled it in pen" loop: a bit more than one lap, never quite closed
    circle(w, h) {
        const cx = w / 2, cy = h / 2;
        const turns = 1.15;
        const start = Math.PI * 0.95;
        return [sample(70, t => {
            const ang = start + t * turns * Math.PI * 2;
            const r = 1 + Math.sin(t * 9) * 0.03 + t * 0.05;
            return [cx + Math.cos(ang) * (w / 2) * 0.96 * r, cy + Math.sin(ang) * (h / 2) * 0.9 * r];
        })];
    },

    // Curved arrow from one corner to the other; dir picks which way it points
    arrow(w, h, dir = 'left') {
        const ends = {
            left: [[w, h * 0.3], [0, h * 0.7]],
            right: [[0, h * 0.3], [w, h * 0.7]],
            'down-left': [[w, 0], [0, h]],
            'down-right': [[0, 0], [w, h]],
            down: [[w * 0.7, 0], [w * 0.4, h]],
            'up-left': [[w, h], [0, 0]],
        }[dir] || [[w, 0], [0, h]];
        const [[x0, y0], [x1, y1]] = ends;
        const mx = (x0 + x1) / 2, my = (y0 + y1) / 2;
        const nx = -(y1 - y0), ny = x1 - x0; // normal for the bend
        const bend = 0.25;
        const cx = mx + nx * bend, cy = my + ny * bend;
        const shaft = sample(30, t => {
            const u = 1 - t;
            return [u * u * x0 + 2 * u * t * cx + t * t * x1, u * u * y0 + 2 * u * t * cy + t * t * y1];
        });
        // Arrowhead from the tangent at the end
        const tx = x1 - cx, ty = y1 - cy;
        const len = Math.hypot(tx, ty) || 1;
        const ux = tx / len, uy = ty / len;
        const size = Math.min(w, h) * 0.35 + 4;
        const side = (s) => [x1 - ux * size + -uy * size * 0.6 * s, y1 - uy * size + ux * size * 0.6 * s];
        return [shaft, [side(1), [x1, y1], side(-1)]];
    },

    star(w, h) {
        const cx = w / 2, cy = h / 2, R = Math.min(w, h) / 2;
        const pts = [];
        for (let i = 0; i <= 5; i++) {
            const a = -Math.PI / 2 + i * (Math.PI * 4 / 5);
            pts.push([cx + Math.cos(a) * R + wobble(R * 0.08), cy + Math.sin(a) * R + wobble(R * 0.08)]);
        }
        return [pts];
    },

    // Four-point twinkle, curved sides
    sparkle(w, h) {
        const cx = w / 2, cy = h / 2;
        return [sample(48, t => {
            const a = t * Math.PI * 2;
            return [cx + Math.cos(a) ** 3 * w / 2, cy + Math.sin(a) ** 3 * h / 2];
        })];
    },

    heart(w, h) {
        return [sample(50, t => {
            const a = t * Math.PI * 2;
            const x = 16 * Math.sin(a) ** 3;
            const y = 13 * Math.cos(a) - 5 * Math.cos(2 * a) - 2 * Math.cos(3 * a) - Math.cos(4 * a);
            return [w / 2 + (x / 34) * w, h * 0.45 - (y / 32) * h];
        })];
    },

    // Two eighth notes
    notes(w, h) {
        const note = (x, y, s) => {
            const head = sample(16, t => [x + Math.cos(t * Math.PI * 2) * s * 0.55, y + Math.sin(t * Math.PI * 2) * s * 0.38]);
            const stem = [[x + s * 0.52, y - s * 0.05], [x + s * 0.55, y - s * 2.2]];
            const flag = sample(10, t => [x + s * 0.55 + t * s * 0.8, y - s * 2.2 + t * s * 0.9 + Math.sin(t * Math.PI) * s * 0.25]);
            return [head, stem, flag];
        };
        const s = h * 0.3;
        return [...note(w * 0.25, h * 0.8, s), ...note(w * 0.68, h * 0.65, s * 0.9)];
    },

    // Paper plane with a looping dashed trail behind it
    plane(w, h) {
        const px = w * 0.62, py = h * 0.1, pw = w * 0.38, ph = h * 0.5;
        const body = [[px, py + ph * 0.55], [px + pw, py], [px + pw * 0.45, py + ph], [px + pw * 0.38, py + ph * 0.62], [px, py + ph * 0.55]];
        const fold = [[px + pw * 0.38, py + ph * 0.62], [px + pw, py]];
        const trail = [];
        const path = t => [px - t * w * 0.6, py + ph * 0.7 + Math.sin(t * Math.PI * 1.6) * h * 0.25 + t * h * 0.1];
        for (let i = 0; i < 5; i++) {
            const a = i / 5 + 0.02, b = a + 0.1;
            trail.push(sample(4, t => path(a + (b - a) * t)));
        }
        return [body, fold, ...trail];
    },

    // Taozi, roughly
    cat(w, h) {
        const cx = w / 2, cy = h * 0.6, rx = w * 0.4, ry = h * 0.36;
        // Head goes from the right ear, around the chin, to the left ear
        const head = sample(40, t => {
            const a = -Math.PI / 2 + 0.45 + t * (Math.PI * 2 - 0.9);
            return [cx + Math.cos(a) * rx, cy + Math.sin(a) * ry];
        });
        const right = head[0], left = head[head.length - 1];
        const earR = [right, [cx + rx * 0.8, cy - ry * 1.6], [cx + rx * 0.9, cy - ry * 0.55]];
        const earL = [left, [cx - rx * 0.8, cy - ry * 1.6], [cx - rx * 0.9, cy - ry * 0.55]];
        const eye = (x) => sample(8, t => [x + Math.cos(t * Math.PI * 2) * w * 0.035, cy - ry * 0.1 + Math.sin(t * Math.PI * 2) * h * 0.04]);
        const mouth = sample(12, t => [cx - rx * 0.2 + t * rx * 0.4, cy + ry * 0.3 + Math.abs(Math.sin(t * Math.PI * 2)) * ry * 0.15]);
        const whisk = (s, dy) => [[cx + s * rx * 0.45, cy + ry * 0.2 + dy], [cx + s * rx * 1.25, cy + ry * 0.05 + dy * 1.6]];
        return [head, earL, earR, eye(cx - rx * 0.35), eye(cx + rx * 0.35), mouth, whisk(-1, 0), whisk(-1, ry * 0.18), whisk(1, 0), whisk(1, ry * 0.18)];
    },

    // A little spiral, the margin classic
    spiral(w, h) {
        return [sample(80, t => {
            const a = t * Math.PI * 2 * 3.2;
            const r = 0.08 + t * 0.92;
            return [w / 2 + Math.cos(a) * r * w / 2, h / 2 + Math.sin(a) * r * h / 2];
        })];
    },
};

export function doodle(name, w, h, opt) {
    const fn = DOODLES[name];
    return fn ? fn(w, h, opt) : [];
}

export function bounds(strokes) {
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    strokes.forEach(s => s.forEach(([x, y]) => {
        if (x < minX) minX = x;
        if (y < minY) minY = y;
        if (x > maxX) maxX = x;
        if (y > maxY) maxY = y;
    }));
    return { minX, minY, maxX, maxY, width: maxX - minX, height: maxY - minY };
}

// Draw strokes onto a 2D canvas (used for the card textures)
export function strokeOnCanvas(ctx, strokes, x, y, scale) {
    ctx.beginPath();
    strokes.forEach(s => s.forEach(([px, py], i) => {
        const X = x + px * scale, Y = y + py * scale;
        if (i === 0) ctx.moveTo(X, Y);
        else ctx.lineTo(X, Y);
    }));
    ctx.stroke();
}
